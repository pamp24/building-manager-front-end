import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { strFromU8, unzipSync } from 'fflate';
import readXlsxFile from 'read-excel-file/node';
import writeXlsxFile from 'write-excel-file/node';
import { mockAuthenticatedSession, mockUserApis, sampleUser } from '../../professionals/professionals.spec-helpers';

test('validates template and invalid rows, maps batch errors and refreshes without database writes', async ({ page }) => {
  const user = { ...sampleUser, role: 'PropertyManager' };
  await mockAuthenticatedSession(page, user);
  await page.route('**/api/v1/**', route => route.fulfill({ json: [] }));
  await mockUserApis(page, user);
  const building = { id: 42, name: 'Test', street1: 'Test', stNumber1: '1', city: 'Athens', floors: 2, undergroundFloorExist: true, halfFloorExist: false, overTopFloorExist: true, parkingSpacesNum: 3, storageNum: 3 };
  await page.route('**/api/v1/buildings/42', route => route.fulfill({ json: building }));
  let gets = 0; let posts = 0; let payload: any[] = [];
  await page.route('**/api/v1/apartments/building/42/list', route => { gets++; return route.fulfill({ json: [] }); });
  await page.route('**/api/v1/apartments/building/42/bulk', async route => {
    posts++; payload = route.request().postDataJSON();
    if (posts === 1) await route.fulfill({ status: 400, json: { errors: [{ row: 2, field: 'number', message: 'Duplicate in batch (row 1)' }] } });
    else await route.fulfill({ json: [1, 2] });
  });
  await page.goto('/pm/buildings/42');
  await page.getByRole('tab', { name: 'Διαμερίσματα' }).click();
  await page.getByRole('button', { name: 'Μαζική Προσθήκη' }).click();
  const upload = page.getByRole('button', { name: 'Ανέβασμα', exact: true });
  await expect(upload).toBeDisabled();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Λήψη προτύπου Excel' }).click();
  const path = await (await downloadPromise).path();
  if (!path) throw new Error('Missing download');
  const buffer = await readFile(path);
  const xml = strFromU8(unzipSync(buffer)['xl/worksheets/sheet1.xml']);
  for (const col of ['D', 'I', 'L', 'N']) expect(xml).toContain(`sqref="${col}2:${col}1001"`);
  const sheets = await readXlsxFile(path);
  expect(sheets[1].data.map(row => row[0]).filter(Boolean)).toEqual(['Υπόγειο', 'Ισόγειο', 'Α', 'Β', 'Δώμα']);
  const input = page.locator('#bulk-apartment-file');
  await input.setInputFiles({ name: 'sample.xlsx', mimeType: 'application/octet-stream', buffer });
  await page.getByRole('button', { name: 'Έλεγχος αρχείου' }).click();
  await expect(page.getByRole('status')).toContainText('επιτυχώς');
  const rows = sheets[0].data; const invalid = [...rows[1]];
  invalid[4] = '-1'; invalid[5] = 1001; invalid[8] = 'Ναι'; invalid[11] = 'Ναι';
  const workbook = async (data: unknown[][]) => writeXlsxFile(data.map(row => row.map(value => ({ value: value as string | number | boolean | null })))).toBuffer();
  await input.setInputFiles({ name: 'invalid.xlsx', mimeType: 'application/octet-stream', buffer: await workbook([rows[0], invalid]) });
  await page.getByRole('button', { name: 'Έλεγχος αρχείου' }).click();
  await expect(page.getByRole('alert')).toContainText('Γραμμή 2, Τ.μ. διαμερίσματος');
  await expect(page.getByRole('alert')).toContainText('Όνομα ενοικιαστή');
  await expect(upload).toBeDisabled();
  const second = [...rows[1]]; second[2] = 'Α2';
  await input.setInputFiles({ name: 'valid.xlsx', mimeType: 'application/octet-stream', buffer: await workbook([rows[0], rows[1], [], second]) });
  await page.getByRole('button', { name: 'Έλεγχος αρχείου' }).click();
  await upload.click();
  await expect(page.getByRole('alert')).toContainText('Γραμμή 4, Αριθμός διαμερίσματος: Duplicate in batch (γραμμή 2)');
  expect(payload[0]).toMatchObject({ buildingId: 42, active: true, enable: true, isManagerHouse: false, isRented: false, parkingSpace: false, apStorageExist: false });
  expect(payload[0]).not.toHaveProperty('ownerId');
  await page.getByRole('button', { name: 'Έλεγχος αρχείου' }).click();
  const before = gets;
  await upload.click();
  await expect(page.getByRole('status')).toContainText('2 διαμερίσματα');
  await expect.poll(() => gets).toBeGreaterThan(before);
  await expect(upload).toBeDisabled();
  expect(posts).toBe(2);
});
